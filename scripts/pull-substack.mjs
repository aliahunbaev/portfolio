// One-time content pull: fetches all public essays from
// playfighter.substack.com and regenerates app/lib/writing.ts.
// Run manually: node scripts/pull-substack.mjs
import { writeFileSync } from "node:fs";

const BASE = "https://playfighter.substack.com";

function decodeEntities(s) {
  return s
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)))
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&nbsp;/g, " ");
}

function htmlToParagraphs(html) {
  let s = html
    .replace(/<(script|style|figure|iframe|audio|video)[\s\S]*?<\/\1>/gi, "")
    // Substack widgets: subscribe/share/button blocks, captioned images.
    .replace(/<p[^>]*class="[^"]*button[^"]*"[\s\S]*?<\/p>/gi, "")
    .replace(/<div[^>]*class="[^"]*(captioned-image|subscription|embedded)[^"]*"[\s\S]*?<\/div>/gi, "")
    .replace(/<blockquote[^>]*>/gi, "")
    .replace(/<\/blockquote>/gi, "")
    .replace(/<br\s*\/?>/gi, "\n");
  const out = [];
  const re = /<(p|h[1-6]|li)[^>]*>([\s\S]*?)<\/\1>/gi;
  let m;
  while ((m = re.exec(s))) {
    const text = decodeEntities(m[2].replace(/<[^>]+>/g, "")).replace(/\s+\n/g, "\n").trim();
    if (!text) continue;
    if (/^(share|subscribe now|leave a comment)$/i.test(text)) continue;
    out.push(m[1] === "li" ? `— ${text}` : text);
  }
  return out;
}

const archive = await (
  await fetch(`${BASE}/api/v1/archive?sort=new&limit=50`)
).json();

const essays = [];
for (const item of archive) {
  if (item.audience !== "everyone" || item.type !== "newsletter") continue;
  const post = await (await fetch(`${BASE}/api/v1/posts/${item.slug}`)).json();
  const paragraphs = htmlToParagraphs(post.body_html ?? "");
  if (!paragraphs.length) continue;
  essays.push({
    slug: post.slug,
    title: post.title,
    subtitle: post.subtitle ?? "",
    date: new Date(post.post_date).toLocaleDateString("en-US", {
      month: "long",
      day: "numeric",
      year: "numeric",
    }),
    paragraphs,
  });
  console.log(`${post.slug}: ${paragraphs.length} paragraphs`);
}

const file = `// Generated by scripts/pull-substack.mjs from playfighter.substack.com —
// do not edit by hand; re-run the script to refresh.

export type Essay = {
  slug: string;
  title: string;
  subtitle: string;
  date: string;
  paragraphs: string[];
};

export function wordCount(essay: Essay) {
  return essay.paragraphs.join(" ").split(/\\s+/).length;
}

export const essays: Essay[] = ${JSON.stringify(essays, null, 2)};
`;
writeFileSync("app/lib/writing.ts", file);
console.log(`\nWrote ${essays.length} essays to app/lib/writing.ts`);
